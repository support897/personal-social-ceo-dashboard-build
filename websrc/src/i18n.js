// The reader: the active language first, English behind it, the
// key itself only if the dictionary has never heard of it (a
// build bug the parity harness hunts — see proof tooling).
export function t(key, vars) {
  let v = (STRINGS[current] && STRINGS[current][key]) ?? STRINGS.en[key] ?? key;
  if (Array.isArray(v)) return v;
  if (vars) {
    v = String(v).replace(/\{(\w+)\}/g, (m, name) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m);
  }
  return v;
}

