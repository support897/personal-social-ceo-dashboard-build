// ------------------------------------------------------------ i18n
// The language layer (Ilse's standing order, 16 Oct 2026; Store
// Review SR-B7): every app reads in the user's own language.
// English is the source of truth; the app follows the device /
// browser language (navigator.language): es* reads Spanish,
// anything else reads English, and a key missing from the active
// language falls back to English — never blank, never a raw key
// on a surface the dictionary covers.
//
// Scope of this wave (the fleet proof wave): the door, the tour,
// the sidebar / nav chrome, Home, Account, Plans and the upgrade
// popup carry their words here, in English + complete Spanish
// (neutral Latin-American Spanish; Mexico is the proof market).
// Room / CEO surfaces do NOT read this module (owner.js never
// imports it, and the room pages keep their own English text).
// Legal wording (the privacy page, checks and disclaimer text)
// is NEVER machine-translated: it is flagged for a human-checked
// translation and stays English in every language this wave —
// see LANGUAGE-FLAGGED.md beside this file's build record.
//
// t(key, vars): {name}-style interpolation. Values may carry
// small markup (<b>) where the English source does. tList(key)
// reads array values (the plan points).

export function resolveLang(input) {
  const l = String(input || "").toLowerCase();
  return l.startsWith("es") ? "es" : "en";
}

function detectLang() {
  try {
    const saved = localStorage.getItem("ruefly.lang");
    if (saved) return resolveLang(saved);
  } catch {}
  return resolveLang((typeof navigator !== "undefined" && navigator.language) || "en");
}

let current = detectLang();
let changeListener = null;

export function lang() { return current; }

export function onLangChange(fn) { changeListener = fn; }

// Switch the active language and re-render through the shell's
// own render path (main.js registers the listener). The choice
// is remembered on this device; the device language stays the
// default everywhere else.
export function setLang(next) {
  current = resolveLang(next);
  try { localStorage.setItem("ruefly.lang", current); } catch {}
  if (changeListener) changeListener(current);
}

